/**
 * Campaign audio uploads (offline-ambience backlog Item 3, 2026-11-25).
 *
 * One home for the law governing locally-hosted ambience files:
 *   • the server-generated upload NAME shape (mirrors the /token-image
 *     doctrine: never trust a client filename — mint `amb-<ts>-<rand><ext>`
 *     and let the pattern be the only name the prune/delete lanes accept);
 *   • the canonical track-row `src` shapes for local tracks:
 *     ('audio/amb-…', campaign-relative upload) or ('/audio/<kebab>.mp3',
 *     root-absolute bundled bed under public/audio/ — Item 3b);
 *   • the supersede prune: when a POST /music save replaces the overrides
 *     map, local rows that VANISHED (save minus track, Reset, category
 *     delete) have their files unlinked — the maps.js token-art prune
 *     discipline, disk-hygiene after the write, never silent, never throwing.
 */
import fs from 'fs';
import path from 'path';
import { campaignAudioDir } from './campaignPaths.js';

const AUDIO_EXTS = ['mp3', 'ogg', 'oga', 'm4a', 'wav'];

// Bare file name generated by the upload route (mirrors token-<ts>-<rand>).
export const AUDIO_FILE_PATTERN = new RegExp(`^amb-\\d+-[a-z0-9]{6}\\.(${AUDIO_EXTS.join('|')})$`);

// Canonical local-track row src (campaign-relative, forward slashes).
export const LOCAL_TRACK_SRC_PATTERN = new RegExp(`^audio/amb-\\d+-[a-z0-9]{6}\\.(${AUDIO_EXTS.join('|')})$`);

// Bundled app-audio beds (offline-ambience backlog Item 3b, 2026-11-25):
// repo-owned CC0 files committed under public/audio/, served by the plain
// express.static lane. The src is root-ABSOLUTE ('/audio/<name>.mp3') — the
// leading slash is what tells client and server "app bundle, not a campaign
// upload". The name charset is the deterministic-kebab shape the bundle ships
// in (town-theme.mp3); mp3/m4a ONLY — Safari cannot decode Ogg Vorbis, so the
// bundle must stay in formats every supported browser plays (see
// public/audio/CREDITS.md).
export const BUNDLED_TRACK_SRC_PATTERN = /^\/audio\/[a-z0-9][a-z0-9-]*\.(?:mp3|m4a)$/;

export const AUDIO_EXTENSIONS_HELP = 'mp3/ogg/oga/m4a/wav only';

export function newAudioFileName(ext) {
  return `amb-${Date.now()}-${Math.random().toString(36).slice(2, 8)}${ext}`;
}

// Set of local-track srcs ('audio/…') referenced by an overrides map.
export function localTrackSrcs(overrides) {
  const found = new Set();
  if (!overrides || typeof overrides !== 'object' || Array.isArray(overrides)) return found;
  for (const tracks of Object.values(overrides)) {
    if (!Array.isArray(tracks)) continue;
    for (const track of tracks) {
      if (track && track.kind === 'local' && typeof track.src === 'string') found.add(track.src);
    }
  }
  return found;
}

/**
 * Unlink stored-but-now-unreferenced audio uploads (runs AFTER the merged
 * music doc persisted — a missed unlink is a disk-hygiene miss, not data
 * loss). Only the upload-name pattern inside the campaign's own audio/ dir
 * is ever touched; every error is console.error'd, never silent.
 */
export function pruneUnreferencedAudio(campaign, storedOverrides, mergedOverrides) {
  const stored = localTrackSrcs(storedOverrides);
  const kept = localTrackSrcs(mergedOverrides);
  const orphans = [...stored].filter((src) => !kept.has(src));
  if (orphans.length === 0) return;
  const audioDir = path.resolve(campaignAudioDir(campaign));
  for (const src of orphans) {
    if (BUNDLED_TRACK_SRC_PATTERN.test(src)) continue; // repo-owned bundle — never prunable
    const file = src.slice('audio/'.length);
    const filePath = path.resolve(audioDir, file);
    if (path.dirname(filePath) !== audioDir || !AUDIO_FILE_PATTERN.test(file)) {
      console.error(`[music] audio prune REFUSED (outside audio dir or foreign name): ${JSON.stringify(src)}`);
      continue;
    }
    try {
      if (fs.existsSync(filePath)) {
        fs.unlinkSync(filePath);
        console.error(`[music] pruned superseded audio upload: ${src}`);
      }
    } catch (e) {
      console.error(`[music] audio prune failed for ${src}:`, e);
    }
  }
}
