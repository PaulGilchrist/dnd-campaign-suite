// @maintained-by-ai
// Disk-anchor lane for categories2024 (src/services/character/featureCategories.js).
// featureCategories.js is DATA, not logic: categories2024 is a curated set of
// name lists consumed by two engines:
//   1. categorizeByCategoryDefinitions / categorizeByCastingTime fallback
//      (featureCategorizationUtils.js) — actions/bonusActions/reactions/
//      characterAdvancement reroute feature rows by EXACT name match.
//   2. display filters (CharActions/CharBonusActions/CharReactions/
//      CharSpecialActions/CharCharacterAdvancement) — featuresToIgnore hides
//      rows by EXACT name match. The categorizer itself never consults
//      featuresToIgnore (FLAG-B, pinned in classRules2024.test.js).
// These tests pin every row of the constant against the real 2024 disk data
// (classes.json feature rows, races.json traits, feats.json benefits) so
// disk↔constant drift fails here instead of silently on the character sheet.
// Factory/selection logic (getCategories identity, 5e rows) belongs to
// featureCategories5e.test.js — not tested here.
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { categories2024 } from './featureCategories.js';

const classes2024 = JSON.parse(readFileSync('public/data/2024/classes.json', 'utf8'))
const races2024 = JSON.parse(readFileSync('public/data/2024/races.json', 'utf8'))
const feats2024 = JSON.parse(readFileSync('public/data/2024/feats.json', 'utf8'))

const {
    featuresToIgnore,
    actions,
    bonusActions,
    reactions,
    characterAdvancement
} = categories2024;

// Every name that any category row must resolve to on disk: class_levels and
// majors feature names, race/subrace trait names, feat names and feat
// benefit names (rules.js addFeatFeatures pushes benefit-named rows, e.g.
// "Luck Points" from the Lucky feat).
const diskRowNames = new Set();
const addRows = (items) => {
    for (const item of (items || [])) {
        if (typeof item?.name === 'string' && item.name) {
            diskRowNames.add(item.name);
        }
    }
};
for (const cls of classes2024) {
    for (const level of (cls.class_levels || [])) addRows(level.features);
    for (const major of (cls.majors || [])) addRows(major.features);
}
for (const race of races2024) {
    addRows(race.traits);
    for (const subrace of (race.subraces || [])) addRows(subrace.traits);
}
for (const feat of feats2024) {
    addRows([feat]);
    addRows(feat.benefits);
}

// Documented dead row: "Feat" matches no disk row and is never generated by
// production code (verified 2026-10 — grep across src/ and public/data/).
// Harmless inert display filter, but pinned so NEW orphan names cannot ride
// in unreviewed; if disk or the wizard ever emits a real "Feat" row, remove
// this allowance.
const KNOWN_DEAD_IGNORE_ROWS = ['Feat'];

const LIST_NAMES = ['featuresToIgnore', 'actions', 'bonusActions', 'reactions', 'characterAdvancement'];

describe('featureCategories2024', () => {
    describe('row shape fidelity', () => {
        it('has exactly the five expected category keys', () => {
            expect(Object.keys(categories2024).sort()).toEqual([...LIST_NAMES].sort());
        });

        it.each(LIST_NAMES)('%s is an array of non-empty trimmed strings with no duplicates', (key) => {
            const list = categories2024[key];
            expect(Array.isArray(list)).toBe(true);
            expect(list.length).toBeGreaterThan(0);
            for (const entry of list) {
                expect(typeof entry).toBe('string');
                expect(entry.trim()).toBe(entry);
                expect(entry.length).toBeGreaterThan(0);
            }
            expect(list).toHaveLength(new Set(list).size);
        });
    });

    describe('constant → disk fidelity (no stale/typo rows)', () => {
        it.each(LIST_NAMES)('every %s name resolves to a real 2024 disk row', (key) => {
            const deadAllowlist = key === 'featuresToIgnore' ? KNOWN_DEAD_IGNORE_ROWS : [];
            const orphans = categories2024[key].filter(name => !diskRowNames.has(name) && !deadAllowlist.includes(name));
            expect(orphans, `rows not found on disk (drift or typo): ${JSON.stringify(orphans)}`).toEqual([]);
        });
    });

    describe('disk → constant fidelity (subclass-selection lane fully covered)', () => {
        it('featuresToIgnore covers every subclass-selection and capstone row emitted by classes.json', () => {
            const uncovered = [];
            for (const cls of classes2024) {
                for (const level of (cls.class_levels || [])) {
                    for (const feature of (level.features || [])) {
                        const isSelectionRow = /Subclass/i.test(feature.name) || feature.name.startsWith('(capstone');
                        if (isSelectionRow && !featuresToIgnore.includes(feature.name)) {
                            uncovered.push(`${cls.name} L${level.level}: "${feature.name}"`);
                        }
                    }
                }
            }
            expect(uncovered, `new disk selection rows missing from featuresToIgnore: ${JSON.stringify(uncovered)}`).toEqual([]);
        });

        it('featuresToIgnore contains the exact 12-class "<Class> Subclass" selection set (disk-enumerated)', () => {
            const diskSelectionNames = classes2024.map(cls => `${cls.name} Subclass`);
            const missing = diskSelectionNames.filter(name => !featuresToIgnore.includes(name));
            expect(missing, `classes.json has ${classes2024.length} classes; missing ignore rows: ${JSON.stringify(missing)}`).toEqual([]);
            // The constant covers exactly these selection headers — nothing more.
            const ignoreSelectionNames = featuresToIgnore.filter(name => / Subclass$/.test(name));
            expect(ignoreSelectionNames).toHaveLength(12);
        });
    });

    describe('exact redirect lanes (each disk-anchored)', () => {
        it('actions is exactly [Naturally Stealthy] (Halfling trait, ct "1 action")', () => {
            expect(actions).toEqual(['Naturally Stealthy']);
        });

        it('bonusActions is exactly ["Nature\'s Veil"] (Ranger L14, ct "1 bonus action")', () => {
            expect(bonusActions).toEqual(["Nature's Veil"]);
        });

        it('reactions is exactly [Beguiling Defenses, Protection] (Archfey major / feat)', () => {
            expect(reactions).toEqual(['Beguiling Defenses', 'Protection']);
        });

        it('Implements of Mercy is in characterAdvancement and not hidden by featuresToIgnore (CLA-181)', () => {
            expect(characterAdvancement).toContain('Implements of Mercy');
            expect(featuresToIgnore).not.toContain('Implements of Mercy');
        });

        it('Magic Initiate benefit rows are ignored via the feat-benefits lane, not classes.json', () => {
            const magicInitiateBenefits = feats2024
                .find(feat => feat.name === 'Magic Initiate')
                .benefits.map(b => b.name);
            for (const benefit of ['Level 1 Spell', 'Two Cantrips', 'Spell Change']) {
                expect(magicInitiateBenefits).toContain(benefit);
                expect(featuresToIgnore).toContain(benefit);
            }
        });
    });

    describe('lane separation (exact-match engines assume disjoint sets)', () => {
        it('featuresToIgnore does not overlap the action-like lanes', () => {
            const actionLike = new Set([...actions, ...bonusActions, ...reactions, ...characterAdvancement]);
            const overlap = featuresToIgnore.filter(name => actionLike.has(name));
            expect(overlap).toEqual([]);
        });

        it('the four action-like lanes are mutually disjoint', () => {
            const all = [...actions, ...bonusActions, ...reactions, ...characterAdvancement];
            expect(all).toHaveLength(new Set(all).size);
        });

        it('does not hide active clickable class features (present on disk, never ignored)', () => {
            // 2024 disk names only ("Ki" is 5e-only — ignored there; 2024 monks
            // use the focus_points numeric field, not a named feature row).
            const activeFeatures = ['Sneak Attack', 'Evasion', 'Uncanny Dodge', 'Second Wind', 'Action Surge', 'Martial Arts'];
            for (const name of activeFeatures) {
                expect(diskRowNames.has(name), `"${name}" should still exist on 2024 disk`).toBe(true);
                expect(featuresToIgnore).not.toContain(name);
            }
        });
    });
});
